import { query } from "./db";
export async function dashboard() {
  const [
    households,
    members,
    locations,
    rooms,
    allocations,
    notifications,
    activity,
    alerts,
    trips,
    stops,
    events,
    weddings,
    dressCategories,
    dressClasses,
    dressSizes,
    memberDress,
  ] = await Promise.all(
    [
      "SELECT h.id,h.name,h.contact,h.mobile,h.email,h.category,h.tags,h.expected,h.additional,h.status,h.delivery,h.assignee,h.visit_date,h.visited_date,h.notes,h.travel,h.stay,h.version,h.sent_at,h.opened_at,d.category_id AS dress_category_id FROM households h LEFT JOIN household_dress d ON d.household_id=h.id WHERE NOT h.archived ORDER BY h.name",
      "SELECT m.*,coalesce((SELECT array_agg(p.display ORDER BY p.phone) FROM member_phones p WHERE p.member_id=m.id),'{}') AS phones FROM members m",
      "SELECT * FROM locations",
      "SELECT r.*,p.name AS property_name,p.address,p.contact,p.instructions FROM rooms r JOIN properties p ON p.id=r.property_id",
      "SELECT * FROM allocations",
      "SELECT * FROM notifications ORDER BY created_at DESC",
      "SELECT * FROM activity ORDER BY created_at DESC LIMIT 500",
      "SELECT * FROM alerts WHERE NOT resolved ORDER BY created_at DESC",
      "SELECT * FROM trips ORDER BY date NULLS LAST",
      "SELECT * FROM stops",
      "SELECT e.*,event_date::text AS event_date FROM events e ORDER BY event_date,starts NULLS LAST",
      "SELECT * FROM wedding",
      "SELECT id,name FROM dress_categories ORDER BY lower(name)",
      "SELECT id,name FROM dress_classes ORDER BY lower(name)",
      "SELECT id,name FROM dress_sizes ORDER BY lower(name)",
      "SELECT * FROM member_dress",
    ].map((s) => query(s)),
  );
  return JSON.parse(
    JSON.stringify({
      households,
      members,
      locations,
      rooms,
      allocations,
      notifications,
      activity,
      alerts,
      trips,
      stops,
      events,
      wedding: weddings[0],
      dressCategories,
      dressClasses,
      dressSizes,
      memberDress,
    }),
  );
}
